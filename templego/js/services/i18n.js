let currentLang = 'zh-TW';

export function setLanguage(lang) {
  if (DICT[lang]) {
    currentLang = lang;
    document.documentElement.lang = lang === 'zh-TW' ? 'zh-Hant-TW' : lang;
  }
}

export function getLanguage() {
  return currentLang;
}

export function t(key) {
  return (DICT[currentLang] && DICT[currentLang][key]) || DICT['zh-TW'][key] || key;
}

export function getTempleField(temple, field) {
  if (!temple) return '';
  if (currentLang === 'zh-TW') {
    return temple[field] || '';
  }
  const localized = temple.i18n && temple.i18n[currentLang];
  if (localized && localized[field] !== undefined) {
    return localized[field];
  }
  return temple[field] || '';
}

export function getSeedTypeLabel(seedDef, field = 'name') {
  if (!seedDef || !seedDef[field]) return '';
  return seedDef[field][currentLang] || seedDef[field]['zh-TW'] || '';
}
